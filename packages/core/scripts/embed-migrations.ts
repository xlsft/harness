// Embeds drizzle-kit SQL migrations (./drizzle/*.sql) into src/db/migrations.generated.ts
// so the bundled server does not need the migrations folder at runtime.
// Run via `pnpm db:generate` after changing src/db/schema.ts.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../drizzle/", import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const migrations = files.map((f) => ({
  id: f.replace(/\.sql$/, ""),
  statements: readFileSync(join(dir, f), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));
const out =
  "// Generated by scripts/embed-migrations.ts. Do not edit.\n" +
  "export const migrations: { id: string; statements: string[] }[] = " +
  JSON.stringify(migrations, null, 2) +
  ";\n";
writeFileSync(new URL("../src/db/migrations.generated.ts", import.meta.url), out);
console.log(`embedded ${migrations.length} migration(s)`);
