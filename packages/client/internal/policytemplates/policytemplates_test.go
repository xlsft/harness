// The committed folder the templates live in.
var committed = filepath.Join("..", "..", "..", "..", "deploy", "mdm")

// handWritten are the files of deploy/mdm that aren't generated.
var handWritten = map[string]bool{"README.md": true}

// The committed templates are what the schema generates now. When this fails, run scripts/policy-templates.sh.
func TestTemplatesAreCurrent(t *testing.T) {
	files, err := Generate(settings.Schema())
	if err != nil {
		t.Fatal(err)
	}
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(committed, filepath.FromSlash(name)))
		if err != nil {
			t.Errorf("deploy/mdm/%s: %v; run scripts/policy-templates.sh", name, err)
			continue
		}
		if !bytes.Equal(got, want) {
			t.Errorf("deploy/mdm/%s is not what policy.schema.json generates: run scripts/policy-templates.sh", name)
		}
	}
	err = filepath.WalkDir(committed, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(committed, path)
		rel = filepath.ToSlash(rel)
		if _, ok := files[rel]; !ok && !handWritten[rel] {
			t.Errorf("deploy/mdm/%s is generated by nothing: remove it, or list it as hand-written here", rel)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

func TestTemplatesAreWellFormed(t *testing.T) {
	files, err := Generate(settings.Schema())
	if err != nil {
		t.Fatal(err)
	}
	for name, content := range files {
		switch filepath.Ext(name) {
		case ".mobileconfig", ".plist", ".admx", ".adml":
			d := xml.NewDecoder(bytes.NewReader(content))
			d.Strict = true
			for {
				_, err := d.Token()
				if err == io.EOF {
					break
				}
				if err != nil {
					t.Fatalf("%s: %v", name, err)
				}
			}
		case ".json":
			if !json.Valid(content) {
				t.Fatalf("%s: not JSON", name)
			}
		}
	}
	if !strings.HasPrefix(string(files["windows/harness.reg"]), "Windows Registry Editor Version 5.00\r\n") {
		t.Fatal("reg header")
	}
}

// What a profile installs is what the client reads: the managed preference file macOS writes from the profile holds the
// keys of mcx_preference_settings at its top level. On macOS, plutil checks the files and converts them like the client.
func TestProfileCarriesTheTemplateKeys(t *testing.T) {
	files, err := Generate(settings.Schema())
	if err != nil {
		t.Fatal(err)
	}
	if runtime.GOOS != "darwin" {
		t.Skip("plutil is macOS only")
	}
	dir := t.TempDir()
	for _, name := range []string{"macos/com.xlsft.harness.mobileconfig", "macos/com.xlsft.harness.plist"} {
		p := filepath.Join(dir, filepath.Base(name))
		if err := os.WriteFile(p, files[name], 0o644); err != nil {
			t.Fatal(err)
		}
		if out, err := exec.Command("/usr/bin/plutil", "-lint", p).CombinedOutput(); err != nil {
			t.Fatalf("%s: %s", name, out)
		}
	}
	out, err := exec.Command("/usr/bin/plutil", "-convert", "json", "-o", "-", "--", filepath.Join(dir, "com.xlsft.harness.mobileconfig")).Output()
	if err != nil {
		t.Fatal(err)
	}
	var profile struct {
		PayloadContent []struct {
			PayloadContent map[string]struct {
				Forced []struct {
					Settings map[string]any `json:"mcx_preference_settings"`
				}
			}
		}
	}
	if err := json.Unmarshal(out, &profile); err != nil {
		t.Fatal(err)
	}
	keys := profile.PayloadContent[0].PayloadContent["com.xlsft.harness"].Forced[0].Settings
	if keys["serverUrl"] != "https://harness.example.com" || keys["disableUpdates"] != false {
		t.Fatalf("profile keys %v", keys)
	}
	pref, err := exec.Command("/usr/bin/plutil", "-convert", "json", "-o", "-", "--", filepath.Join(dir, "com.xlsft.harness.plist")).Output()
	if err != nil {
		t.Fatal(err)
	}
	var plain map[string]any
	if err := json.Unmarshal(pref, &plain); err != nil {
		t.Fatal(err)
	}
	if plain["serverUrl"] != keys["serverUrl"] {
		t.Fatalf("preference file %v", plain)
	}
}

// The ADMX names a policy for every single value, and the registry values it writes read back as the keys.
func TestADMXCoversTheSingleValues(t *testing.T) {
	s := settings.Schema()
	files, err := Generate(s)
	if err != nil {
		t.Fatal(err)
	}
	admx, adml := string(files["windows/harness.admx"]), string(files["windows/en-US/harness.adml"])
	for _, k := range s.Keys() {
		if admxKind(k.SchemaProperty) == "" {
			if !strings.Contains(adml, k.Path) {
				t.Errorf("%s: the Settings policy doesn't mention it", k.Path)
			}
			continue
		}
		if !strings.Contains(admx, `valueName="`+k.Path+`"`) {
			t.Errorf("%s: no policy writes it", k.Path)
		}
		n := policyName(k.Path)
		if !strings.Contains(adml, `<string id="`+n+`">`) || !strings.Contains(adml, `<string id="`+n+`_Explain">`) {
			t.Errorf("%s: no strings", k.Path)
		}
	}
	for _, ref := range []string{"$(presentation.", "$(string."} {
		for rest := admx; ; {
			i := strings.Index(rest, ref)
			if i < 0 {
				break
			}
			rest = rest[i+len(ref):]
			id := rest[:strings.Index(rest, ")")]
			if !strings.Contains(adml, `id="`+id+`"`) {
				t.Errorf("ADMX refers to %s%s), which the ADML doesn't define", ref, id)
			}
		}
	}
}

