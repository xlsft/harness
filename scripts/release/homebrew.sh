#!/usr/bin/env bash
# Homebrew files for a release, from the release's own checksums.txt: Formula/harness-client.rb (the client) and
# Casks/harness.rb (the app). They go into the tap repository (default xlsft/homebrew-harness), so people run
#   brew install xlsft/harness/harness-client
#   brew install --cask xlsft/harness/harness
# Writes files only; scripts/release/homebrew-publish.sh pushes them, and only the release workflow runs that.
#
# Usage: homebrew.sh <tag> <directory with checksums.txt> <output directory> [signing]
#   signing is unsigned, signed or notarized (assemble.sh's), for what the cask says about the first open.
# Platforms are macOS only for now; a Linux client archive in checksums.txt would add an on_linux block here.
set -euo pipefail
tag="${1:?usage: homebrew.sh <tag> <directory> <output directory> [signing]}"
dist="${2:?usage: homebrew.sh <tag> <directory> <output directory> [signing]}"
out="${3:?usage: homebrew.sh <tag> <directory> <output directory> [signing]}"
signing="${4:-unsigned}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
repo="${GITHUB_REPOSITORY:-xlsft/harness}"

"$root/scripts/release/parse-version.sh" "$tag" >/dev/null
version="${tag#v}"
if [[ "$version" == *-* ]]; then
  echo "homebrew.sh: $tag is a pre-release; the tap follows stable releases only" >&2
  exit 1
fi
sums="$dist/checksums.txt"
[[ -f "$sums" ]] || { echo "homebrew.sh: no checksums.txt in $dist" >&2; exit 1; }

sha() {
  local name="$1" s
  s="$(awk -v n="$name" '$2 == n || $2 == "*" n { print $1 }' "$sums" | head -n1)"
  [[ "$s" =~ ^[0-9a-f]{64}$ ]] || { echo "homebrew.sh: checksums.txt has no sha256 for $name" >&2; exit 1; }
  echo "$s"
}
client_arm="$(sha "harness-client_${version}_darwin_arm64.tar.gz")"
client_intel="$(sha "harness-client_${version}_darwin_amd64.tar.gz")"
app_arm="$(sha "harness_${version}_darwin_arm64.dmg")"
app_intel="$(sha "harness_${version}_darwin_amd64.dmg")"
download="https://github.com/$repo/releases/download/v"

mkdir -p "$out/Formula" "$out/Casks"

cat >"$out/Formula/harness-client.rb" <<EOF
# Generated by scripts/release/homebrew.sh in $repo for $tag. The next release replaces this file; change the script.
class HarnessClient < Formula
  desc "Agent client of xlsft\`s harness: agent loop, tools, permissions and sandbox"
  homepage "https://harness.xlsft.com"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "${download}#{version}/harness-client_#{version}_darwin_arm64.tar.gz"
      sha256 "$client_arm"
    end
    on_intel do
      url "${download}#{version}/harness-client_#{version}_darwin_amd64.tar.gz"
      sha256 "$client_intel"
    end
  end

  def install
    bin.install "harness-client"
    generate_completions_from_executable(bin/"harness-client", "completion")
  end

  def caveats
    <<~EOS
      Sign in to your server, then check the machine:
        harness-client login https://your-harness-server
        harness-client doctor
      Homebrew keeps it up to date (brew upgrade); harness-client update refuses a Homebrew install.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/harness-client version")
    assert_match "harness-client", shell_output("#{bin}/harness-client completion bash")
  end
end
EOF

first_open=""
if [[ "$signing" != notarized ]]; then
  first_open='
  caveats <<~EOS
    This release of the app is not notarized by Apple, so macOS blocks its first open.
    Open it once, then allow it in System Settings > Privacy & Security (Open Anyway).
    https://github.com/'"$repo"'/blob/main/docs/release.md#opening-an-app-that-isnt-notarized
  EOS'
fi

cat >"$out/Casks/harness.rb" <<EOF
# Generated by scripts/release/homebrew.sh in $repo for $tag. The next release replaces this file; change the script.
cask "harness" do
  arch arm: "arm64", intel: "amd64"

  version "$version"
  sha256 arm:   "$app_arm",
         intel: "$app_intel"

  url "${download}#{version}/harness_#{version}_darwin_#{arch}.dmg"
  name "xlsft\`s harness"
  desc "Coding agent with any model, on a server you own"
  homepage "https://harness.xlsft.com"

  # The app updates itself (Settings > About); Homebrew leaves it to that.
  auto_updates true

  app "xlsft\`s harness.app"

  zap trash: [
    "~/Library/Application Support/dev.xlsft.harness",
    "~/Library/Caches/dev.xlsft.harness",
    "~/Library/Preferences/dev.xlsft.harness.plist",
    "~/Library/Saved Application State/dev.xlsft.harness.savedState",
    "~/Library/WebKit/dev.xlsft.harness",
  ]
$first_open
end
EOF

echo "Wrote $out/Formula/harness-client.rb and $out/Casks/harness.rb for $tag"
